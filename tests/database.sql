do $$
declare row public.invoices; same public.invoices; blocked boolean:=false; own public.invoices;
begin
 select * into row from public.invoices where invoice_number='INTEGRATION-001';
 insert into test_results values('Manager can see team invoice',row.id is not null);
 row:=public.decide_invoice(row.id,'approved','Verified order against the request');
