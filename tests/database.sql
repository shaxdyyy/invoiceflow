 blocked:=false;begin perform public.finish_review(row.id,result.run_id,'wrong','{"mode":"rules"}');exception when others then blocked:=true;end;
 insert into test_results values('Forged review result blocked',blocked);
 result:=public.finish_review(row.id,result.run_id,'integration-review-only','{"mode":"rules","summary":"Mismatch","tokens":0,"trace":[]}');
