 perform public.amend_invoice(row.id,jsonb_set(payload,'{total}','500'));
 insert into test_results values('Correction retains original details',exists(select 1 from public.activity where invoice_id=row.id and event='invoice_corrected' and details->'before'->>'total'='700.00'));
 result:=public.start_review(row.id);
 blocked:=false;begin perform public.finish_review(row.id,gen_random_uuid(),'integration-review-only','{"mode":"rules"}');exception when others then blocked:=true;end;
 insert into test_results values('Stale review completion blocked',blocked);
 result:=public.finish_review(row.id,result.run_id,'integration-review-only','{"mode":"rules","summary":"Checks passed","tokens":0,"trace":[]}');
 insert into test_results values('Valid review reaches human approval',result.status='pending_approval' and result.checks->>'passed'='true');
 blocked:=false;begin perform public.decide_invoice(row.id,'approved','Employee tries to approve');exception when others then blocked:=true;end;
 insert into test_results values('Employee approval denied',blocked);
 blocked:=false;begin update public.invoices set status='approved' where id=row.id;exception when others then blocked:=true;end;
 insert into test_results values('Direct table mutation denied',blocked);
 payload:=jsonb_set(payload,'{invoice_number}','"INTEGRATION-RETRY"');payload:=jsonb_set(payload,'{invoice_date}','"2026-10-02"');payload:=jsonb_set(payload,'{total}','500');
 row:=public.create_invoice(payload,gen_random_uuid());
 result:=public.start_review(row.id);result:=public.finish_review(row.id,result.run_id,'integration-review-only','{"mode":"ai","summary":"Unavailable","tokens":0,"error":"model unavailable"}');
