begin
 payload:='{"supplier":"Integration Supplies","invoice_number":"INTEGRATION-001","invoice_date":"2026-10-01","due_date":"2026-10-15","category":"Office supplies","items":[{"description":"Notebook","quantity":10,"unit_price":50}],"tax":0,"total":700,"notes":"Transactional test"}'::jsonb;
