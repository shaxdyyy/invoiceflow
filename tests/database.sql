insert into test_ids(name) values ('manager'),('employee'),('outsider');
create temporary table test_results (name text,passed boolean);
grant select on test_ids to authenticated;
grant select,insert on test_results to authenticated;
insert into auth.users(id,aud,role,email,raw_user_meta_data) select id,'authenticated','authenticated',name||'-integration@example.invalid',jsonb_build_object('name',name) from test_ids;
update private.settings set value=encode(extensions.digest('integration-review-only','sha256'),'hex') where key='review_hash';
update private.settings set value=encode(extensions.digest('integration-setup-only','sha256'),'hex') where key='setup_hash';
set local role authenticated;
select set_config('request.jwt.claim.sub',(select id::text from test_ids where name='manager'),true);
select public.ensure_profile();
select public.claim_manager('integration-setup-only');
insert into test_results values('Owner setup code activates manager',private.is_manager());
select set_config('request.jwt.claim.sub',(select id::text from test_ids where name='employee'),true);
select public.ensure_profile();
do $$
